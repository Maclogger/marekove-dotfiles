#!/usr/bin/env bash
#
# Makes this machine reachable over SSH from my other devices via Tailscale:
#
#   * installs Tailscale and starts tailscaled at boot
#   * installs /etc/ssh/sshd_config.d/10-marek.conf (keys only, user marek)
#   * starts sshd at boot
#   * ufw: SSH only over the tailscale0 interface (drops the default
#     "allow 22 from anywhere" rule), plus Tailscale's UDP port for direct
#     peer-to-peer connections
#
# Installed BY COPY, never with stow: sshd config must not be a symlink into
# this user-writable repo, or editing the repo would be a path to root.
#
# Run with sudo. Re-run after editing the config here. Afterwards, log in to
# Tailscale once with:  sudo tailscale up --operator=marek
set -euo pipefail
here=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)

[[ $EUID -eq 0 ]] || { echo "run this with sudo" >&2; exit 1; }

pacman -S --needed --noconfirm tailscale
systemctl enable --now tailscaled

# Host keys are normally generated by sshdgenkeys.service on first sshd start,
# but `sshd -t` below refuses to validate without them.
ssh-keygen -A

# Validate the config before sshd ever loads it.
install -o root -g root -m 0644 \
  "$here/etc/ssh/sshd_config.d/10-marek.conf" /etc/ssh/sshd_config.d/10-marek.conf
if ! sshd -t; then
  rm -f /etc/ssh/sshd_config.d/10-marek.conf
  echo "sshd config failed validation; removed it, sshd not enabled" >&2
  exit 1
fi
systemctl enable --now sshd
systemctl reload sshd

ufw allow in on tailscale0 to any port 22 proto tcp comment 'ssh over tailscale'
ufw allow 41641/udp comment 'tailscale direct connections'
ufw delete allow 22/tcp || true

# Public keys of the devices allowed in go here, one per line.
user_home=/home/marek
install -d -o marek -g marek -m 0700 "$user_home/.ssh"
touch "$user_home/.ssh/authorized_keys"
chown marek:marek "$user_home/.ssh/authorized_keys"
chmod 0600 "$user_home/.ssh/authorized_keys"

echo
systemctl --no-pager --lines=0 status tailscaled sshd | grep -E '●|Active:'
echo
ufw status | grep -E '22|41641'
echo
echo "Next: sudo tailscale up --operator=marek   (opens a login link)"
